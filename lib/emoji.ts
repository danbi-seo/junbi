/**
 * 제목에서 분류 이모지를 추천한다. 강제하지 않고 추천만 한다.
 * 사용자가 직접 고르면 그게 우선이다.
 */
export function suggestEmoji(title: string): string | null {
  const t = title.trim();
  if (!t) return null;
  for (const [words, emoji] of RULES) {
    if (words.some((w) => t.includes(w))) return emoji;
  }
  return null;
}
